"""Tests for Phase 2 ingest and normalization.

Runs are generated by the simulator (the only supported input) into a temporary
directory. Ground truth is written to a separate tree so these tests also prove
that ingest has no path to it.
"""

from __future__ import annotations

import builtins
import csv
import io
import shutil
from pathlib import Path
from typing import Any

import pandas as pd
import pytest
from typer.testing import CliRunner

import prometheus.cli as cli
from prometheus.contracts import SUBSYSTEMS, Subsystem
from prometheus.ingest import IngestError, conversion_for, ingest_run
from prometheus.ingest.spec import iter_layouts
from prometheus.sim import load_scenario, simulate, write_run

SCENARIO = "battery_voltage_drop"
SEED = 7
POWER_INTERVAL = 10
THERMAL_INTERVAL = 30


@pytest.fixture(scope="module")
def mission(tmp_path_factory: pytest.TempPathFactory) -> dict[str, Any]:
    """Generate one mission once for the whole module."""
    root = tmp_path_factory.mktemp("ingest")
    run = simulate(load_scenario(SCENARIO), SEED)
    run_dir = root / "generated" / f"{SCENARIO}_{SEED}"
    truth_dir = root / "ground_truth" / f"{SCENARIO}_{SEED}"
    written = write_run(run, run_dir, truth_dir)
    return {"run_dir": run_dir, "truth_dir": truth_dir, "written": written}


@pytest.fixture(scope="module")
def ingested(mission: dict[str, Any]):
    return ingest_run(mission["run_dir"])


def _copy_mission(mission: dict[str, Any], tmp_path: Path) -> Path:
    target = tmp_path / "mission"
    shutil.copytree(mission["run_dir"], target)
    return target


def _data_lines(path: Path) -> list[str]:
    return path.read_text(encoding="utf-8").splitlines()


def _write_lines(path: Path, lines: list[str]) -> None:
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _channel(spec, name: str):
    return next(channel for channel in spec.channels if channel.name == name)


def test_spec_parsing(ingested) -> None:
    spec = ingested.spec
    assert spec.scenario == SCENARIO
    assert spec.seed == SEED
    assert spec.duration_s == 21600
    assert spec.time_origin_utc.isoformat() == "2026-03-14T00:00:00+00:00"

    assert len(spec.channels) == 18
    assert set(spec.channel_names) == set(ingested.series)
    assert len(spec.dependencies) == 7

    for subsystem, layout in spec.subsystems.items():
        assert layout.subsystem is subsystem
        for channel in layout.channels:
            assert channel.subsystem is subsystem
            assert channel.name == f"{subsystem.value}.{channel.source_name}"
            assert channel.name in ingested.series

    battery_temp = _channel(spec, "power.battery_temp_c")
    assert battery_temp.name == "power.battery_temp_c"
    assert (battery_temp.original_unit, battery_temp.unit) == ("C", "K")

    dependent = next(
        dependency
        for dependency in spec.dependencies
        if dependency.source is Subsystem.THERMAL
        and dependency.target is Subsystem.POWER
    )
    assert (dependent.lag_min_s, dependent.lag_max_s) == (300.0, 900.0)


def test_units_convert_to_canonical_units(ingested, mission: dict[str, Any]) -> None:
    spec = ingested.spec
    battery_temp = _channel(spec, "power.battery_temp_c")
    assert battery_temp.nominal_min == pytest.approx(268.15)
    assert battery_temp.nominal_max == pytest.approx(298.15)

    downlink = _channel(spec, "comms.downlink_rate_kbps")
    assert (downlink.original_unit, downlink.unit) == ("kbps", "bit/s")
    assert downlink.nominal_min == pytest.approx(180_000.0)
    assert downlink.nominal_max == pytest.approx(320_000.0)

    raw = pd.read_csv(mission["run_dir"] / "telemetry_power.csv")
    celsius = raw["battery_temp_c"].to_numpy(dtype=float)
    kelvin = ingested.series["power.battery_temp_c"].values
    assert kelvin == pytest.approx(celsius + 273.15)

    raw_comms = pd.read_csv(mission["run_dir"] / "telemetry_comms.csv")
    kbps = raw_comms["downlink_rate_kbps"].to_numpy(dtype=float)
    bit_per_s = ingested.series["comms.downlink_rate_kbps"].values
    assert bit_per_s == pytest.approx(kbps * 1000.0)

    unknown = conversion_for("furlongs")
    assert (unknown.original, unknown.canonical) == ("furlongs", "furlongs")
    assert unknown.known is False
    assert conversion_for("C").known is True
    assert unknown.apply(pd.Series([1.0, 2.0]).to_numpy()) == pytest.approx([1.0, 2.0])
    assert ingested.quality.unknown_units == []


def test_timestamps_align_on_one_utc_timeline(ingested) -> None:
    spec = ingested.spec
    expected_rows = {
        Subsystem.POWER: 2161,
        Subsystem.THERMAL: 721,
        Subsystem.COMMS: 1081,
        Subsystem.ADCS: 4321,
    }
    for layout in iter_layouts(spec):
        series = ingested.series[layout.channels[0].name]
        assert len(series.timestamp) == expected_rows[layout.subsystem]
        assert series.timestamp.tz is not None
        assert str(series.timestamp.tz) == "UTC"
        assert series.timestamp[0].isoformat() == "2026-03-14T00:00:00+00:00"
        for channel in layout.channels:
            assert ingested.series[channel.name].timestamp.equals(series.timestamp)

    deltas = ingested.timeline.to_series().diff().dropna().dt.total_seconds()
    assert set(deltas.unique()) == {5.0}
    assert ingested.timeline.is_monotonic_increasing
    assert ingested.timeline.is_unique

    native = {
        stamp
        for series in ingested.series.values()
        for stamp in series.timestamp
    }
    assert set(ingested.timeline) == native
    assert ingested.rows_by_subsystem == expected_rows


def test_aligned_view_fills_only_within_one_interval(ingested) -> None:
    view = ingested.aligned(max_gap_factor=1.0)
    power_name = "power.bus_voltage_v"
    thermal_name = "thermal.avionics_temp_k"

    t0 = view.timestamps[0]
    t5 = view.timestamps[1]
    t10 = view.timestamps[2]
    assert t0.minute == 0 and t5.second == 5 and t10.second == 10

    # Power samples every 10 s: the 5 s row is carried from t=0, not observed.
    assert view.frame.loc[t5, power_name] == pytest.approx(
        view.frame.loc[t0, power_name]
    )
    assert not bool(view.observed.loc[t5, power_name])
    assert bool(view.observed.loc[t10, power_name])
    assert bool(view.observed.loc[t0, power_name])

    # Thermal samples every 30 s: t=5 is still within its interval tolerance.
    assert view.frame.loc[t5, thermal_name] == pytest.approx(
        view.frame.loc[t0, thermal_name]
    )
    assert not bool(view.observed.loc[t5, thermal_name])
    assert view.frame.shape == (4321, 18)
    assert view.observed.shape == view.frame.shape


def test_gap_is_detected_and_not_extrapolated(mission, tmp_path: Path) -> None:
    run_dir = _copy_mission(mission, tmp_path)
    thermal = run_dir / "telemetry_thermal.csv"
    lines = _data_lines(thermal)
    removed = [lines.pop(2), lines.pop(2)]  # drop t=30 s, then t=60 s
    _write_lines(thermal, lines)

    result = ingest_run(run_dir)
    assert result.quality.gap_count == 1
    assert result.quality.max_spacing_s == pytest.approx(90.0)

    gap_time = pd.to_datetime(1773446445, unit="s", utc=True)
    view = result.aligned(max_gap_factor=1.0)
    assert all(
        pd.to_datetime(int(line.split(",")[0]), unit="s", utc=True)
        not in result.series["thermal.avionics_temp_k"].timestamp
        for line in removed
    )
    assert pd.isna(view.frame.loc[gap_time, "thermal.avionics_temp_k"])
    assert not bool(view.observed.loc[gap_time, "thermal.avionics_temp_k"])

    wide = result.aligned(max_gap_factor=2.0)
    assert not pd.isna(wide.frame.loc[gap_time, "thermal.avionics_temp_k"])
    assert not bool(wide.observed.loc[gap_time, "thermal.avionics_temp_k"])


def test_duplicate_timestamps_are_counted_and_first_wins(mission, tmp_path: Path) -> None:
    run_dir = _copy_mission(mission, tmp_path)
    power = run_dir / "telemetry_power.csv"
    lines = _data_lines(power)
    lines.append(lines[1])  # repeat the first data row
    _write_lines(power, lines)

    result = ingest_run(run_dir)
    assert result.quality.duplicate_timestamps == 1
    assert result.quality.rows_read == result.quality.rows_kept + 1
    assert len(result.series["power.bus_voltage_v"].timestamp) == 2161


def test_out_of_range_values_are_counted(ingested) -> None:
    report = ingested.quality
    assert report.out_of_range > 0
    voltage = next(
        channel for channel in report.channels if channel.channel == "power.bus_voltage_v"
    )
    assert voltage.out_of_range > 0
    assert voltage.nominal_min == pytest.approx(27.0)
    assert voltage.nominal_max == pytest.approx(29.0)

    conversions = {item.split(":")[0]: item for item in report.unit_conversions}
    assert conversions["power.battery_temp_c"].endswith("C -> K")
    assert conversions["comms.downlink_rate_kbps"].endswith("kbps -> bit/s")
    assert "data quality" in report.render()


def test_events_are_tagged_and_sorted(ingested) -> None:
    events = ingested.events
    assert len(events) == 8
    assert all(event.subsystem in SUBSYSTEMS for event in events)
    assert all(event.timestamp.tzinfo is not None for event in events)
    assert events == sorted(events, key=lambda event: (event.timestamp, event.event_id))
    assert {event.kind for event in events} <= {"command", "alarm"}


def test_ingest_never_opens_ground_truth(mission, monkeypatch: pytest.MonkeyPatch) -> None:
    opened: list[Path] = []
    real_builtin_open = builtins.open
    real_io_open = io.open

    def guard(file: Any, *args: Any, **kwargs: Any) -> Any:
        path = Path(file) if not isinstance(file, int) else Path(str(file))
        opened.append(path)
        if "ground_truth" in path.parts or "ground_truth" in path.name:
            raise AssertionError(f"ingest opened ground truth: {path}")
        return real_builtin_open(file, *args, **kwargs)

    def io_guard(file: Any, *args: Any, **kwargs: Any) -> Any:
        path = Path(file) if not isinstance(file, int) else Path(str(file))
        opened.append(path)
        if "ground_truth" in path.parts or "ground_truth" in path.name:
            raise AssertionError(f"ingest opened ground truth: {path}")
        return real_io_open(file, *args, **kwargs)

    monkeypatch.setattr(builtins, "open", guard)
    monkeypatch.setattr(io, "open", io_guard)

    assert mission["truth_dir"].is_dir()
    ingest_run(mission["run_dir"])
    assert opened
    assert any(path.name == "specs.yaml" for path in opened)
    assert not any("ground_truth" in path.parts for path in opened)


def test_missing_column_is_a_clear_error(mission, tmp_path: Path) -> None:
    run_dir = _copy_mission(mission, tmp_path)
    power = run_dir / "telemetry_power.csv"
    with power.open(encoding="utf-8", newline="") as handle:
        rows = list(csv.reader(handle))
    index = rows[0].index("bus_voltage_v")
    for row in rows:
        del row[index]
    with power.open("w", encoding="utf-8", newline="") as handle:
        csv.writer(handle, lineterminator="\n").writerows(rows)

    with pytest.raises(IngestError, match="missing columns"):
        ingest_run(run_dir)


